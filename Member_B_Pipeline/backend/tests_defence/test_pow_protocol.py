async def test_load_estimate_counts_previous_second(redis_client):
    sec = 1_000_000
    for _ in range(50):
        await record_and_get(redis_client, "t", "ev", 100, now=sec - 1)  # traffic in the previous second
    load = await record_and_get(redis_client, "t", "ev", 100, now=sec)
    assert load == pytest.approx(0.5, abs=0.02)
    for _ in range(300):
        await record_and_get(redis_client, "t", "ev", 100, now=sec - 1)
    assert await record_and_get(redis_client, "t", "ev", 100, now=sec) == 1.0  # capped
    assert await record_and_get(redis_client, "t", "other-event", 100, now=sec) == 0.0  # per event


async def test_load_estimate_expires_and_survives_redis_failure():
    class Dead:
        def pipeline(self, **_):
            raise ConnectionError("down")

    assert await record_and_get(Dead(), "t", "ev", 100) == 0.0  # never blocks entry
