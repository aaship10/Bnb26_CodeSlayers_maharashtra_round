ROOT = Path(__file__).resolve().parents[2]
VECTORS = json.loads((ROOT / "docs" / "pow_vectors.json").read_text(encoding="utf-8"))
KEY = "k" * 40
E, U = uuid.UUID(int=1), uuid.UUID(int=2)
NOW = 1_800_000_000


def mint(**kw):
    args = dict(kind="p", event_id=E, user_id=U, exp=NOW + 60, bits=8, pow_ok=False)
    args.update(kw)
    return protocol.mint(KEY, **args)


# ------------------------------------------------------------------ the PoW rule itself
@pytest.mark.parametrize("v", VECTORS["rule_vectors"], ids=lambda v: f"{v['prefix'][:12]}-{v['bits']}")
def test_independent_rule_vectors(v):
    """Vectors generated by scripts/gen_pow_vectors.py (plain hashlib, integer maths)."""
    assert hashlib.sha256(f"{v['prefix']}:{v['nonce']}".encode()).hexdigest() == v["sha256"]
    assert protocol.solution_ok(v["prefix"], v["nonce"], v["bits"])
    n = int(v["nonce"])
    if n > 0:  # it is the SMALLEST: nothing below satisfies it
        assert not any(protocol.solution_ok(v["prefix"], str(i), v["bits"]) for i in range(n))
    assert protocol.solve(v["prefix"], v["bits"]) == v["nonce"]


def test_frontend_vectors_agree_with_the_backend():
    """Member D's solver vectors (from their own Python tool): cross-implementation check."""
    src = (ROOT.parent / "frontend" / "src" / "features" / "challenge" / "pow.vectors.ts")
    if not src.exists():
        pytest.skip("frontend not present next to Member_B_Pipeline")
    rows = re.findall(r"prefix: '([^']*)', bits: (\d+), nonce: '(\d+)'", src.read_text(encoding="utf-8"))
    assert len(rows) >= 25
    for prefix, bits, nonce in rows:
        assert protocol.solution_ok(prefix, nonce, int(bits)), (prefix, bits, nonce)
        if int(nonce) > 0:
            assert not protocol.solution_ok(prefix, str(int(nonce) - 1), int(bits))  # theirs is minimal too


def test_leading_zero_bits_matches_integer_arithmetic():
    rng = random.Random(5)
    for _ in range(500):
        d = bytes(rng.getrandbits(8) if rng.random() > 0.3 else 0 for _ in range(32))
        assert protocol.leading_zero_bits(d) == 256 - int.from_bytes(d, "big").bit_length()
    assert protocol.leading_zero_bits(bytes(32)) == 256
    assert protocol.leading_zero_bits(b"\x80" + bytes(31)) == 0
    assert protocol.leading_zero_bits(b"\x01" + bytes(31)) == 7


