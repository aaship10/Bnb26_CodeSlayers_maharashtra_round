def test_a_captcha_challenge_carries_a_signed_pow_ok_bit_that_cannot_be_flipped():
    c1 = mint(kind="c", bits=0, pow_ok=True)
    assert protocol.check(c1, KEY, U, E, NOW)[1].pow_ok is True
    flipped = c1.replace(".c1.", ".c0.", 1)
    assert protocol.check(flipped, KEY, U, E, NOW)[0] is protocol.Status.FORGED
    c0 = mint(kind="c", bits=0, pow_ok=False)
    assert protocol.check(c0.replace(".c0.", ".c1.", 1), KEY, U, E, NOW)[0] is protocol.Status.FORGED


def test_mint_validates_its_inputs():
    with pytest.raises(ValueError):
        protocol.mint(KEY, "x", E, U, NOW, 8)
    with pytest.raises(ValueError):
        protocol.mint(KEY, "p", E, U, NOW, 100)


def test_solving_what_was_minted():
    t = mint(bits=12)
    n = protocol.solve(t, 12)
    assert protocol.solution_ok(t, n, 12) and not protocol.solution_ok(t, n, 40)


def test_verification_is_cheap():
    t = mint(bits=8)
    n = protocol.solve(t, 8)
    start = time.perf_counter()
    for _ in range(2000):
        protocol.check(t, KEY, U, E, NOW)
        protocol.solution_ok(t, n, 8)
    per_call_us = (time.perf_counter() - start) / 2000 * 1e6
    assert per_call_us < 500, f"verification took {per_call_us:.0f} microseconds"  # one HMAC + one SHA-256


# ------------------------------------------------------------------------ adaptive difficulty
def test_difficulty_is_monotone_and_capped():
    cfg = PowLayer(base_bits=14, risk_bits_max=6, load_bits_max=2, max_bits=20)
    grid = [i / 20 for i in range(21)]
    for load in grid:
        bits = [difficulty(cfg, risk, load) for risk in grid]
        assert bits == sorted(bits)  # more risk never easier
    for risk in grid:
        bits = [difficulty(cfg, risk, load) for load in grid]
        assert bits == sorted(bits)  # more load never easier
    assert difficulty(cfg, 0, 0) == 14 and difficulty(cfg, 1, 1) == 20 and max(difficulty(cfg, 5, 5), 0) == 20


def test_difficulty_is_clamped_for_out_of_range_inputs():
    cfg = PowLayer()
    assert difficulty(cfg, -3, -3) == cfg.base_bits
    assert difficulty(cfg, 9, 9) == min(cfg.base_bits + cfg.risk_bits_max + cfg.load_bits_max, cfg.max_bits)


def test_difficulty_never_exceeds_max_bits():
    assert difficulty(PowLayer(base_bits=14, max_bits=15, risk_bits_max=6, load_bits_max=2), 1, 1) == 15


