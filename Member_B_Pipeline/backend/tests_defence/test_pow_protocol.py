# -------------------------------------------------------------------------- token format
@pytest.mark.parametrize("t", VECTORS["token_vectors"]["tokens"], ids=lambda t: f"{t['kind']}{t['pow_ok']}-{t['bits']}")
def test_token_vectors(t):
    tv = VECTORS["token_vectors"]
    got = protocol.mint(tv["key"], t["kind"], uuid.UUID(tv["event_hex"]), uuid.UUID(tv["user_hex"]), t["exp"], t["bits"],
                        bool(t["pow_ok"]), nonce=t["nonce"])
    assert got == t["token"]
    status, tok = protocol.check(t["token"], tv["key"], uuid.UUID(tv["user_hex"]), uuid.UUID(tv["event_hex"]), 1_000_000_000)
    assert status is protocol.Status.OK and tok.bits == t["bits"] and tok.pow_ok == bool(t["pow_ok"])
    if "solution" in t:
        assert protocol.solution_ok(t["token"], t["solution"], t["bits"])


def test_token_shape_and_length():
    t = mint()
    assert re.fullmatch(r"fd1\.p0\.[0-9a-f]{32}\.[0-9a-f]{32}\.\d+\.\d+\.[0-9a-f]{16}\.[0-9a-f]{24}", t)
    assert 126 <= len(t) <= 130  # bounded prefix: documented in POW_SPEC.md


def test_round_trip_and_binding():
    t = mint()
    status, tok = protocol.check(t, KEY, U, E, NOW)
    assert status is protocol.Status.OK and (tok.kind, tok.bits, tok.exp, tok.pow_ok) == ("p", 8, NOW + 60, False)
    assert protocol.check(t, KEY, uuid.UUID(int=3), E, NOW)[0] is protocol.Status.WRONG_BINDING  # another user
    assert protocol.check(t, KEY, U, uuid.UUID(int=3), NOW)[0] is protocol.Status.WRONG_BINDING  # another event


def test_expiry_boundary():
    t = mint(exp=NOW)
    assert protocol.check(t, KEY, U, E, NOW)[0] is protocol.Status.OK
    assert protocol.check(t, KEY, U, E, NOW + 1)[0] is protocol.Status.EXPIRED


def test_challenges_are_unique_even_with_identical_inputs():
    assert len({mint() for _ in range(200)}) == 200


@pytest.mark.parametrize(
    "mutate",
    [
        lambda t: t.replace(".8.", ".0.", 1),  # lowering the difficulty
        lambda t: t.replace(".p0.", ".p1.", 1),  # claiming the PoW is done
        lambda t: t.replace(".p0.", ".c0.", 1),  # changing the kind
        lambda t: t[:-1] + ("0" if t[-1] != "0" else "1"),  # last MAC character
        lambda t: t.replace("fd1.", "fd2.", 1),
        lambda t: t + "0",
        lambda t: t[:-4],
        lambda t: "",
        lambda t: "garbage",
        lambda t: t.upper(),
    ],
)
def test_any_tampering_is_forged(mutate):
    assert protocol.check(mutate(mint()), KEY, U, E, NOW)[0] is protocol.Status.FORGED


